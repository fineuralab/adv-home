#!/usr/bin/env python3
"""Rasterize the Roboto ASCII subset for the LCD, with two-bit coverage."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets/fonts/Roboto[wdth,wght].ttf"
DEST = ROOT / "core/font_data.h"


def main():
    out = ["// ADV Home UI Raster, derived from Roboto.\n",
           "// Copyright 2011 The Roboto Project Authors (https://github.com/googlefonts/roboto-classic)\n",
           "// SPDX-License-Identifier: OFL-1.1\n",
           "// See assets/fonts/OFL.txt for the full license.\n",
           "// Generated by tools/generate_fonts.py.\n#pragma once\n#include <stdint.h>\n",
           "namespace homefont {\n",
           "struct Glyph { uint16_t offset; uint8_t w,h,advance; int8_t x,y; };\n",
           "struct Face { const uint8_t *pixels; const Glyph *glyphs; uint8_t ascent,height; };\n"]
    total = 0
    faces = [("Small", 10, 400), ("Body", 12, 400), ("Title", 17, 500),
             ("Heading", 12, 500), ("Readout", 17, 400)]
    for name, size, weight in faces:
        font = ImageFont.truetype(str(SOURCE), size)
        font.set_variation_by_axes([
            weight if axis["name"] == b"Weight" else axis["default"]
            for axis in font.get_variation_axes()
        ])
        ascent, descent = font.getmetrics()
        pixels, glyphs = [], []
        for code in range(32, 127):
            char = chr(code)
            left, top, right, bottom = font.getbbox(char, anchor="ls")
            w, h = right - left, bottom - top
            image = Image.new("L", (max(1, w), max(1, h)))
            ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor="ls")
            glyphs.append((len(pixels), w, h, round(font.getlength(char)), left, top))
            samples = [(value * 3 + 127) // 255 for value in image.tobytes()] if w * h else []
            for start in range(0, len(samples), 4):
                value = 0
                for i, sample in enumerate(samples[start:start+4]):
                    value |= sample << (6 - i * 2)
                pixels.append(value)
        out.append(f"static const uint8_t {name}Pixels[] = {{\n")
        for start in range(0, len(pixels), 24):
            out.append("  " + ",".join(f"0x{v:02x}" for v in pixels[start:start+24]) + ",\n")
        out.append("};\n")
        out.append(f"static const Glyph {name}Glyphs[] = {{\n")
        out.extend("  {" + ",".join(map(str, g)) + "},\n" for g in glyphs)
        out.append("};\n")
        out.append(f"static const Face {name} = {{{name}Pixels, {name}Glyphs, {ascent}, {ascent+descent}}};\n")
        total += len(pixels) + len(glyphs) * 8
    out.append("} // namespace homefont\n")
    DEST.write_text("".join(out))
    print(f"Generated {len(faces)} raster faces, approximately {total} bytes")


if __name__ == "__main__":
    main()
